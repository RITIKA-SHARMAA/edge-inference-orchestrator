"""Compare calibration choices for static INT8 quantization of MobileNetV2.

For each combination of calibration images and calibration method, quantize the model
with ONNX Runtime and measure, on the evaluation crops:
  - top-1 agreement: INT8 picks the same class as FP32
  - top-5 containment: FP32's class is among INT8's five best
Results go to docs/QUANTIZATION-NOTES.md. Uses ONNX Runtime from Python directly.

Run after prepare_data.py: python scripts/calibration_experiment.py
"""

import tempfile
from pathlib import Path

import numpy as np
import onnx
import onnxruntime as ort
from onnx import version_converter
from onnxruntime.quantization import (
    CalibrationDataReader,
    CalibrationMethod,
    QuantFormat,
    QuantType,
    quantize_static,
)
from onnxruntime.quantization.shape_inference import quant_pre_process

from common import DATA, MODELS, ROOT
from prepare_data import EVAL_IMAGES, crops


class Images(CalibrationDataReader):
    def __init__(self, batch):
        self.items = iter(batch[:, None])

    def get_next(self):
        item = next(self.items, None)
        return None if item is None else {"input": item}


def outputs(model_path: str, X: np.ndarray) -> np.ndarray:
    session = ort.InferenceSession(model_path, providers=["CPUExecutionProvider"])
    return np.stack([session.run(None, {"input": x[None]})[0][0] for x in X])


if __name__ == "__main__":
    X = np.load(DATA / "mobilenet" / "X.npy")
    fp32 = outputs(str(MODELS / "mobilenetv2.onnx"), X)
    reference = fp32.argmax(1)

    calibration_sets = {
        "6 unrelated images (galaxy, retina, logo, coins, camera, text page)":
            np.load(DATA / "mobilenet" / "calib.npy"),
        "different crops of the 7 evaluation photos": crops(EVAL_IMAGES, seed=7),
    }
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        onnx.save(version_converter.convert_version(onnx.load(MODELS / "mobilenetv2.onnx"), 13),
                  tmp / "opset13.onnx")
        quant_pre_process(str(tmp / "opset13.onnx"), str(tmp / "prep.onnx"))
        for set_name, images in calibration_sets.items():
            for method in [CalibrationMethod.MinMax, CalibrationMethod.Percentile]:
                quantize_static(str(tmp / "prep.onnx"), str(tmp / "int8.onnx"), Images(images),
                                quant_format=QuantFormat.QDQ, per_channel=True,
                                activation_type=QuantType.QUInt8, weight_type=QuantType.QInt8,
                                calibrate_method=method)
                int8 = outputs(str(tmp / "int8.onnx"), X)
                top1 = float(np.mean(int8.argmax(1) == reference))
                top5 = float(np.mean([reference[i] in np.argsort(-int8[i])[:5] for i in range(len(X))]))
                rows.append((set_name, method.name, top1, top5))
                print(f"{set_name} | {method.name} | {top1:.3f} | {top5:.3f}")

    margins = np.sort(fp32, axis=1)
    close = float(np.mean((margins[:, -1] - margins[:, -2]) < 1.0))
    lines = [
        "# Quantization notes: choosing the calibration",
        "",
        "Generated by `scripts/calibration_experiment.py`. MobileNetV2, static INT8 (QDQ, per-channel",
        f"weights), evaluated on {len(X)} crops. Agreement is measured against the FP32 model.",
        "",
        "| Calibration images | Method | Top-1 agreement | FP32 class in INT8 top-5 |",
        "|---|---|---|---|",
    ]
    lines += [f"| {s} | {m} | {t1 * 100:.1f}% | {t5 * 100:.1f}% |" for s, m, t1, t5 in rows]
    lines += [
        "",
        "## What this showed",
        "",
        "- I expected calibration images that look like the evaluation photos to help most. In this run",
        "  they did not: the best result was Percentile on the unrelated images, while on the photo crops",
        "  Percentile was slightly worse than MinMax.",
        f"- With {len(X)} crops, one crop is {100 / len(X):.1f} percentage points, so differences of a few",
        "  points are one or two images and not conclusive. The clear result is the top-5 column: INT8",
        "  almost always keeps FP32's answer among its five best classes.",
        "- MinMax uses each activation's full observed range, so a few extreme values can stretch the scale",
        "  and leave fewer INT8 steps for typical values. Percentile clips the most extreme 0.001% first.",
        f"- {close * 100:.0f}% of evaluation crops have FP32's top two logits within 1.0 of each other, so small",
        "  quantization errors can swap the top-1 class while the right answer stays in the top 5.",
        "- `scripts/quantize.py` uses the 6 unrelated calibration images with Percentile, the best row here.",
        "- Caveats: one small evaluation set from sample photos (not ImageNet), one machine, one run.",
    ]
    (ROOT / "docs" / "QUANTIZATION-NOTES.md").write_text("\n".join(lines) + "\n")
