"""Load benchmark results into SQLite and write docs/BENCHMARK.md.

  python scripts/report.py [--session ID]

results/bench.jsonl (one line per eio_bench run) -> results/bench.db table `runs`
-> docs/BENCHMARK.md for one benchmark session (the latest by default).
Numbers are copied as measured; nothing is rounded in a favourable direction.
"""

import argparse
import json
import sqlite3
from datetime import datetime, timezone

from common import RESULTS, ROOT

COLUMNS = ["tag", "model", "backend", "size_bytes", "samples", "accuracy", "accuracy_top5", "reference", "warmup",
           "runs", "p50_ms", "p95_ms", "mean_ms", "ort_intra_op_threads", "os", "cpu",
           "hardware_threads", "compiler", "timestamp"]


def load_db() -> sqlite3.Connection:
    db = sqlite3.connect(RESULTS / "bench.db")
    db.execute("DROP TABLE IF EXISTS runs")
    db.execute(f"CREATE TABLE runs ({', '.join(COLUMNS)}, session TEXT, precision TEXT, family TEXT)")
    for line in (RESULTS / "bench.jsonl").read_text().splitlines():
        row = json.loads(line)
        family, precision, session = (row["tag"].split(":") + ["", ""])[:3]
        db.execute(
            f"INSERT INTO runs VALUES ({', '.join('?' * (len(COLUMNS) + 3))})",
            [row.get(c) for c in COLUMNS] + [session, precision, family],
        )
    db.commit()
    return db


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--session")
    args = parser.parse_args()
    db = load_db()
    session = args.session or db.execute(
        "SELECT session FROM runs ORDER BY timestamp DESC LIMIT 1").fetchone()[0]
    rows = db.execute(
        "SELECT family, precision, size_bytes, p50_ms, p95_ms, mean_ms, accuracy, reference, samples, "
        "runs, warmup, cpu, hardware_threads, os, compiler, ort_intra_op_threads, timestamp, accuracy_top5 "
        "FROM runs WHERE session = ? ORDER BY family DESC, precision", (session,)).fetchall()
    if not rows:
        raise SystemExit(f"no rows for session {session}")

    by = {(r[0], r[1]): r for r in rows}
    first = rows[0]
    when = datetime.fromtimestamp(first[16], tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        "# Benchmark: FP32 vs INT8",
        "",
        "Generated by `scripts/report.py` from `results/bench.db`. Do not edit by hand.",
        "",
        f"- Machine: {first[11]}, {first[12]} hardware threads, {first[13]}",
        f"- Compiler: {first[14]}; ONNX Runtime 1.20.1, CPU backend, {first[15]} intra-op thread(s)",
        f"- Session `{session}`, {when}. Batch size 1; {first[10]} warm-up runs, then {first[9]} timed runs.",
        "",
        "| Model | Precision | Size | p50 latency | p95 latency | Mean | Top-1 | Top-5 | Samples | Measured against |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        ref = "true labels" if r[7] == "ground_truth" else "FP32 model's top-1 (agreement)"
        out.append(f"| {r[0]} | {r[1].upper()} | {r[2] / 1e6:.2f} MB | {r[3]:.3f} ms | {r[4]:.3f} ms | "
                   f"{r[5]:.3f} ms | {r[6] * 100:.1f}% | {r[17] * 100:.1f}% | {r[8]} | {ref} |")

    out += ["", "## INT8 compared with FP32", ""]
    for family in sorted({r[0] for r in rows}, reverse=True):
        fp32, int8 = by.get((family, "fp32")), by.get((family, "int8"))
        if not (fp32 and int8):
            continue
        size = 100 * (1 - int8[2] / fp32[2])
        p50 = int8[3] / fp32[3]
        out.append(f"- **{family}**: {size:.1f}% smaller; p50 latency x{p50:.2f} of FP32 "
                   f"({'faster' if p50 < 1 else 'slower'}); top-1 {int8[6] * 100:.1f}% vs {fp32[6] * 100:.1f}%, "
                   f"top-5 {int8[17] * 100:.1f}% vs {fp32[17] * 100:.1f}%.")

    out += [
        "",
        "## How to read this",
        "",
        "- **p50** is the median run; **p95** is the time 95% of runs finish within, which shows the slow tail.",
        "- MobileNetV2 has no labelled test set here, so its INT8 accuracy is the share of evaluation crops where",
        "  INT8 picks the same top-1 class as FP32 (FP32 is 100% against itself by definition), and its top-5",
        "  figure is how often FP32's choice is among INT8's five best classes.",
        "- INT8 is only faster when the CPU has fast 8-bit instructions and the model is big enough for",
        "  compute to dominate. For the tiny digits MLP, quantize/dequantize overhead can outweigh the saving.",
        "- These numbers come from one machine; rerun `python scripts/benchmark.py` to measure yours.",
    ]
    path = ROOT / "docs" / "BENCHMARK.md"
    path.write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
